def _fetch_list(tag, samples, dest, timeout=30.0, quiet=True):
    import urllib.parse
    import urllib.request

    dest.mkdir(parents=True, exist_ok=True)
    got = []
    for fname, url in samples:
        target = dest / fname
        if not (target.exists() and target.stat().st_size > 0):
            try:
                req = urllib.request.Request(urllib.parse.quote(url, safe=":/"),
                                             headers={"User-Agent": "brush-bridge-tests"})
                with urllib.request.urlopen(req, timeout=timeout) as r:
                    data = r.read()
                part = target.with_name(target.name + ".part")
                part.write_bytes(data)
                part.replace(target)
                if not quiet:
                    print(f"[{tag}] downloaded {fname} ({len(data)} bytes)")
            except Exception as exc:  # offline or the file moved
                if not quiet:
                    print(f"[{tag}] FAILED {fname}: {exc}")
                continue
        if target.exists():
            got.append(target)
    return got


def fetch_krita(timeout: float = 30.0, quiet: bool = True):
    """Download the Krita reference presets/bundles (skips files already present)."""
    return _fetch_list("krita", KRITA_SAMPLES, krita_samples_dir(), timeout, quiet)


def fetch_gimp(timeout: float = 30.0, quiet: bool = True):
    """Download the GIMP reference brushes (skips files already present)."""
    return _fetch_list("gimp", GIMP_SAMPLES, gimp_samples_dir(), timeout, quiet)


