def procreate_samples_dir():
    from pathlib import Path as _P

    return _P(__file__).resolve().parent.parent / "tests" / "fixtures" / "downloaded" / "procreate"


def fetch_procreate(timeout: float = 20.0, quiet: bool = True):
    """Download the Procreate samples (skips files already present). Returns the local paths."""
    import urllib.request
    import zipfile as _zip

    dest = procreate_samples_dir()
    dest.mkdir(parents=True, exist_ok=True)
    got = []
    for fname, url, _lic in PROCREATE_SAMPLES:
        target = dest / fname
        if not (target.exists() and _zip.is_zipfile(target)):
            try:
                req = urllib.request.Request(url, headers={"User-Agent": "brush-bridge-tests"})
                with urllib.request.urlopen(req, timeout=timeout) as r:
                    data = r.read()
                part = target.with_suffix(target.suffix + ".part")
                part.write_bytes(data)
                part.replace(target)
                if not quiet:
                    print(f"[procreate] downloaded {fname} ({len(data)} bytes)")
            except Exception as exc:  # offline or the repository vanished
                if not quiet:
                    print(f"[procreate] FAILED {fname}: {exc}")
                continue
        if target.exists():
            got.append(target)
    return got


